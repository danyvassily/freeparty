const DICTS: Record<UILanguage, Dict> = { fr, en, es: en, de: en, it: en, pt: en };

export function translate(lang: UILanguage, key: string): string {
  return DICTS[lang]?.[key] ?? DICTS.en[key] ?? DICTS.fr[key] ?? key;
}

/** Détecte la langue du navigateur (repli fr) */
export function detectBrowserLanguage(): UILanguage {
  if (typeof navigator === "undefined") return "fr";
  const nav = navigator.languages?.[0] ?? navigator.language ?? "fr";
  const base = nav.split("-")[0].toLowerCase() as UILanguage;
  return (SUPPORTED_LANGUAGES as readonly string[]).includes(base) ? base : "fr";
}
